function multimodalModule(mm: MultimodalSignals | undefined): string {
  if (!mm) return '';
  // 동의 세션 ID 없으면 주입 거부 — 코드 레벨 안전장치
  if (!mm.consentSessionId) return '';

  const parts: string[] = [
    '## 비언어 신호 (쌍방 동의 하에 수집된 녹음/영상 분석 결과)',
    '아래 신호는 텍스트가 놓치는 정보입니다. 통역에 반영하되, 비언어 신호도 반드시 가설로만 제시합니다.',
    '("경멸하고 있다" ❌ → "이 한숨은 지친 마음의 신호일 수도, 답답함의 표현일 수도 있어요" ⭕)',
  ];
  if (mm.toneAnalysis) parts.push(`- 어조: ${mm.toneAnalysis}`);
  if (mm.visualCues) parts.push(`- 표정/자세: ${mm.visualCues}`);
  return parts.join('\n');
}

