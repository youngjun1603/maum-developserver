/** 트랙: 심리상담(EFT/애착) | 기독교(Powlison/Keller/Tripp) */
export type Track = 'psychology' | 'christian';

/** 통역 모드: 수신 | 발신 | 중재 | 관점 */
export type Mode = 'receive' | 'send' | 'mediate' | 'perspective';

/** 감정 깊이 (심리상담 트랙): 1=표면 ~ 3=심층 */
export type EmotionDepth = 1 | 2 | 3;

/** 신학 강도 (기독교 트랙): 1=통합형 ~ 3=순수 성경형 */
export type TheologyLevel = 1 | 2 | 3;

/** 목양 톤 (기독교 트랙): 'grace'=경청·은혜형(기본) | 'direct'=제한적 직면형 */
export type PastoralTone = 'grace' | 'direct';

/** 관계 기억 프로파일 (D1에서 조회해 주입) */
export interface RelationshipMemory {
  /** 반복 갈등 주제 (예: ["시가", "돈", "육아"]) */
  recurringTopics?: string[];
  /** 심리상담 프로파일: 애착 경향·갈등 스타일·자주 나타난 4독소 */
  psychologyProfile?: string;
  /** 기독교 프로파일: 반복되는 마음의 우상 패턴·성화 주제 */
  christianProfile?: string;
  /** 성공 공식: 효과 있었던 표현들 */
  successPatterns?: string[];
  /** 상대 관점 프로파일: 배우자가 자주 상처받는 지점·인식 습관 */
  partnerPerspective?: string;
}

/** 멀티모달 분석 결과 (음성/영상 → 비언어 신호, 동의 게이트 통과 후에만) */
export interface MultimodalSignals {
  /** 어조 분석 (예: "대화 시작 30초 내 음량 상승, 빠른 말속도") */
  toneAnalysis?: string;
  /** 표정/자세 (예: "팔짱, 시선 회피 3회, 한숨 2회") */
  visualCues?: string;
  /** 동의 세션 ID — 없으면 멀티모달 데이터 주입 자체를 거부 */
  consentSessionId: string;
}

/** 통역 요청 설정 */
export interface TranslationConfig {
  track: Track;
  mode: Mode;
  /** 사용자 입력 (배우자의 말 / 내가 하고 싶은 말 / 대화 전체) */
  input: string;
  /** 심리상담 트랙 슬라이더 */
  emotionDepth?: EmotionDepth;
  /** 기독교 트랙 슬라이더 */
  theologyLevel?: TheologyLevel;
  pastoralTone?: PastoralTone;
  /** 관계 기억 (없으면 첫 사용) */
  memory?: RelationshipMemory;
  /** 멀티모달 신호 (동의 게이트 통과분만) */
  multimodal?: MultimodalSignals;
  /** 사용자 성별/호칭 맥락 (선택, 예: "아내 입장") */
  userContext?: string;
}

